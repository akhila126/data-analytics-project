import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
df=pd.read_csv("/content/india_retail_sales_10000.csv")
df

# 1. Monthly sales trend
monthly = df.groupby("Order_Month", as_index=False)["Sales_INR"].sum()
plt.figure(figsize=(12,5))
sns.lineplot(data=monthly, x="Order_Month", y="Sales_INR", marker="o")
plt.title("Monthly Revenue Trend")
plt.xlabel("Month"); plt.ylabel("Revenue (INR)")
plt.xticks(rotation=45); plt.tight_layout(); plt.show()

# 2. Revenue by product category
category = df.groupby("Category", as_index=False)["Sales_INR"].sum().sort_values("Sales_INR", ascending=False)
plt.figure(figsize=(9,5))
sns.barplot(data=category, x="Sales_INR", y="Category")
plt.title("Revenue by Product Category")
plt.xlabel("Revenue (INR)"); plt.ylabel("")
plt.tight_layout(); plt.show()

# 3. Profit by category
profit_cat = df.groupby("Category", as_index=False)["Profit_INR"].sum().sort_values("Profit_INR", ascending=False)
plt.figure(figsize=(9,5))
sns.barplot(data=profit_cat, x="Profit_INR", y="Category")
plt.title("Profit Contribution by Category")
plt.xlabel("Profit (INR)"); plt.ylabel("")
plt.tight_layout(); plt.show()

# 4. Sales by state
state_sales = df.groupby("State", as_index=False)["Sales_INR"].sum().sort_values("Sales_INR", ascending=False)
plt.figure(figsize=(10,5))
sns.barplot(data=state_sales, x="Sales_INR", y="State")
plt.title("Revenue by State")
plt.xlabel("Revenue (INR)"); plt.ylabel("")
plt.tight_layout(); plt.show()

# 5. Sales channel mix
channel = df.groupby("Sales_Channel")["Sales_INR"].sum().sort_values(ascending=False)
plt.figure(figsize=(7,7))
plt.pie(channel, labels=channel.index, autopct="%1.1f%%", startangle=90)
plt.title("Revenue Share by Sales Channel")
plt.tight_layout(); plt.show()

# 6. Discount vs profit
plt.figure(figsize=(9,5))
sns.scatterplot(data=df.sample(min(2500, len(df)), random_state=42),
                x="Discount_Pct", y="Profit_INR", hue="Category", alpha=.65)
plt.title("Discount Level vs Order Profit")
plt.xlabel("Discount (decimal; e.g. 0.10 = 10%)")
plt.ylabel("Profit per order (INR)")
plt.tight_layout(); plt.show()

# 7. Return rate by category
returns = df.groupby("Category", as_index=False)["Returned"].mean()
returns["Return_Rate_Pct"] = returns["Returned"] * 100
plt.figure(figsize=(9,5))
sns.barplot(data=returns, x="Return_Rate_Pct", y="Category")
plt.title("Return Rate by Category")
plt.xlabel("Return rate (%)"); plt.ylabel("")
plt.tight_layout(); plt.show()

# 8. Customer age distribution
plt.figure(figsize=(9,5))
sns.histplot(data=df, x="Age", bins=18, kde=True)
plt.title("Customer Age Distribution")
plt.xlabel("Age"); plt.ylabel("Order count")
plt.tight_layout(); plt.show()

