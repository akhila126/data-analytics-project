print(f"Orders: {df['Order_ID'].nunique():,}")
print(f"Unique customers: {df['Customer_ID'].nunique():,}")
print(f"Average order value: ₹{df['Sales_INR'].mean():,.2f}")
print(f"Overall profit margin: {df['Profit_INR'].sum()/df['Sales_INR'].sum()*100:.2f}%")
print(f"Return rate: {df['Returned'].mean()*100:.2f}%")